"""Printable PDF for an authorized, SAVED local E-Way Bill.

A local E-Way Bill is not an NIC-issued EBN. Never generate a fake official
number, barcode, QR code, portal validity, or official status from draft data.
"""
from decimal import Decimal, InvalidOperation
from html import escape
from io import BytesIO
import re

from django.http import HttpResponse
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

INK = colors.HexColor("#1B2937")
MUTED = colors.HexColor("#62748A")
BLUE = colors.HexColor("#195A9F")
LIGHT = colors.HexColor("#EDF5FB")
LINE = colors.HexColor("#D9E4EC")


def _safe(value, default="—"):
    text = str(value).strip() if value is not None else ""
    return text[:500] if text else default


def _para(value, style):
    return Paragraph(escape(_safe(value)).replace("\n", "<br/>"), style)


def _amount(value):
    try:
        amount = Decimal(str(value or 0))
        return amount if amount.is_finite() else Decimal("0")
    except (ValueError, TypeError, InvalidOperation):
        return Decimal("0")


def _currency(value):
    return "INR {:,.2f}".format(_amount(value))


def _party_table(party, title, p, width):
    party = party if isinstance(party, dict) else {}
    data = [
        [p(title, "heading")],
        [p(party.get("tradeName"), "body")],
        [p("GSTIN / URP: " + _safe(party.get("gstin")), "small")],
        [p(party.get("address"), "small")],
        [p(", ".join(filter(None, [
            str(party.get("place") or ""),
            str(party.get("pincode") or ""),
            "State " + str(party.get("stateCode") or "") if party.get("stateCode") else "",
        ])), "small")],
    ]
    card = Table(data, colWidths=[width], hAlign="LEFT")
    card.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), LIGHT),
        ("BOX", (0, 0), (-1, -1), .5, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 9),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return card


def create_eway_bill_pdf(saved):
    """Render all saved E-Way Bill fields, with a clear local/official distinction."""
    data = saved.payload if isinstance(saved.payload, dict) else {}
    out = BytesIO()
    doc = SimpleDocTemplate(
        out, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm,
        topMargin=17 * mm, bottomMargin=17 * mm,
        title="E-Way Bill Local Record - " + _safe(data.get("documentNo"), "Draft"),
        author="CubeGears",
    )
    base = getSampleStyleSheet()
    styles = {
        "title": ParagraphStyle("ew-title", parent=base["Heading1"],
                                fontSize=17, leading=21, textColor=INK, spaceAfter=7),
        "heading": ParagraphStyle("ew-heading", parent=base["Normal"],
                                  fontName="Helvetica-Bold", fontSize=9,
                                  leading=12, textColor=BLUE, spaceAfter=5),
        "body": ParagraphStyle("ew-body", parent=base["Normal"],
                               fontSize=9, leading=13, textColor=INK),
        "small": ParagraphStyle("ew-small", parent=base["Normal"],
                                fontSize=7.8, leading=11, textColor=MUTED),
        "cell": ParagraphStyle("ew-cell", parent=base["Normal"],
                               fontSize=7.5, leading=10, textColor=INK),
        "header": ParagraphStyle("ew-header", parent=base["Normal"],
                                 fontName="Helvetica-Bold", fontSize=7.5,
                                 leading=10, textColor=colors.white),
    }
    P = lambda value, name="body": _para(value, styles[name])
    story = [P("E-Way Bill — Saved Record", "title")]
    # A locally prepared document must not look like an NIC-issued EBN.
    if saved.number:
        story.append(P("NIC E-Way Bill Number: " + _safe(saved.number), "heading"))
    else:
        story.append(P("LOCAL DRAFT / READY FOR API — Not generated by the GST/NIC portal", "heading"))
    story.extend([
        P("Document: {} · {} · {}".format(
            _safe(data.get("documentType")), _safe(data.get("documentNo")),
            _safe(data.get("documentDate")))),
        P("Movement: {} / {} · Transaction: {}".format(
            _safe(data.get("supplyType")), _safe(data.get("subSupplyType")),
            _safe(data.get("transactionType"))), "small"),
        P("Status: " + _safe(saved.status), "small"),
        Spacer(1, 12),
    ])
    gap = 8
    col_width = (doc.width - gap) / 2
    parties = Table([[
        _party_table(data.get("from"), "FROM / DISPATCH", P, col_width),
        _party_table(data.get("to"), "TO / DESTINATION", P, col_width),
    ]], colWidths=[col_width + gap / 2, col_width + gap / 2])
    parties.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), gap),
    ]))
    story.extend([parties, Spacer(1, 13), P("3. Goods Details", "heading")])
    headers = ["HSN / Item Code", "Product / Description", "Qty / Unit", "Taxable", "GST %", "CESS %"]
    rows = [[P(h, "header") for h in headers]]
    taxable = cgst = sgst = igst = cess = Decimal("0")
    for item in (data.get("items") or [])[:75]:
        if not isinstance(item, dict):
            continue
        amount = _amount(item.get("taxableValue"))
        cgst_rate = _amount(item.get("cgstRate"))
        sgst_rate = _amount(item.get("sgstRate"))
        igst_rate = _amount(item.get("igstRate"))
        cess_rate = _amount(item.get("cessRate"))
        taxable += amount
        cgst += amount * cgst_rate / 100
        sgst += amount * sgst_rate / 100
        igst += amount * igst_rate / 100
        cess += amount * cess_rate / 100
        gst_rate = cgst_rate + sgst_rate + igst_rate
        rows.append([
            P(item.get("hsnCode"), "cell"),
            P("{} {}".format(_safe(item.get("productName"), ""),
                             _safe(item.get("description"), "")), "cell"),
            P("{} {}".format(_safe(item.get("qty"), "0"),
                             _safe(item.get("unit"), "")), "cell"),
            P(_currency(amount), "cell"),
            P("{:g}".format(gst_rate), "cell"),
            P("{:g}".format(cess_rate), "cell"),
        ])
    widths = [25*mm, 65*mm, 23*mm, 30*mm, 18*mm, 18*mm]
    goods_table = Table(rows, colWidths=widths, repeatRows=1, hAlign="LEFT")
    goods_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), INK),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
        ("LINEBELOW", (0, -1), (-1, -1), .5, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 7),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
    ]))
    story.extend([goods_table, Spacer(1, 10)])
    other = _amount(data.get("otherAmount"))
    nonadval = _amount(data.get("cessNonAdvolAmount"))
    total = taxable + cgst + sgst + igst + cess + other + nonadval
    summary = [
        ["Taxable", taxable], ["CGST", cgst], ["SGST", sgst], ["IGST", igst],
        ["CESS", cess], ["CESS Non-Advol", nonadval], ["Other Amount", other], ["TOTAL", total],
    ]
    summary_table = Table([[P(k, "cell"), P(_currency(v), "cell")] for k,v in summary],
                          colWidths=[doc.width * .67, doc.width * .33], hAlign="LEFT")
    summary_table.setStyle(TableStyle([
        ("LINEBELOW", (0, -2), (-1, -2), .6, BLUE),
        ("BACKGROUND", (0, -1), (-1, -1), LIGHT),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    transport = data.get("transport") or {}
    if not isinstance(transport, dict):
        transport = {}
    story.extend([
        summary_table, Spacer(1, 12),
        P("4. Transportation Details", "heading"),
        P("Mode: {} · Distance: {} km · Transporter: {} · ID: {}".format(
            _safe(transport.get("mode")), _safe(transport.get("distanceKm"), "0"),
            _safe(transport.get("transporterName")), _safe(transport.get("transporterId")))),
        P("Transport Document: {} · Date: {}".format(
            _safe(transport.get("transportDocNo")), _safe(transport.get("transportDocDate"))), "small"),
        Spacer(1, 9), P("5. Vehicle Details", "heading"),
        P("Vehicle: {} · Type: {} · Entered From: {}".format(
            _safe(transport.get("vehicleNo")), _safe(transport.get("vehicleType")),
            _safe(data.get("enteredFrom")))),
        P("Entered By: {} · CEWB: {}".format(
            _safe(data.get("enteredBy")), _safe(data.get("cewbNo"))), "small"),
        Spacer(1, 9), P("Remarks", "heading"), P(data.get("notes"), "body"),
        Spacer(1, 8),
        P("This PDF is a copy of the saved CubeGears record; it does not create an official GST/NIC E-Way Bill.", "small"),
    ])
    doc.build(story)
    return out.getvalue()


def eway_pdf_response(saved):
    data = create_eway_bill_pdf(saved)
    number = str((saved.payload or {}).get("documentNo") or str(saved.pk))
    safe = re.sub(r"[^A-Za-z0-9_-]+", "-", number)[:75].strip("-") or "record"
    response = HttpResponse(data, content_type="application/pdf")
    response["Content-Disposition"] = 'attachment; filename="EWayBill-{}.pdf"'.format(safe)
    response["Cache-Control"] = "private, no-store"
    response["X-Content-Type-Options"] = "nosniff"
    return response
